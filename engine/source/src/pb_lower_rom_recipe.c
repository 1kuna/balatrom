static uint8_t recipe_overlaps(const void *a,uint16_t alen,const void *b,uint16_t blen){
 uintptr_t aa=(uintptr_t)a,bb=(uintptr_t)b;
 return aa<=bb?bb-aa<alen:aa-bb<blen;
}
uint8_t pb_lower_rom_recipe(const PBOverlayPalettes *p,const uint8_t *pixels,
                           uint8_t maximum,uint16_t *out) BANKED {
 uint16_t a=0,b=0,lo,hi,mid,r;uint8_t i,c,profile;
 if(!p||!pixels||!out||maximum>2u||recipe_overlaps(out,2,p,56)||recipe_overlaps(out,2,pixels,128))return 0;
 for(profile=0;profile<2u;profile++)if(!memcmp(p,palette_keys[profile],56))break;
 if(profile==2u)return 0;
 lo=profile_offsets[profile];hi=profile_offsets[profile+1u];
 for(i=0;i<128u;i++){
  c=pixels[i];if(c>20u||!recipe_bits[c]){*out=65535u;return 1;}
  if(i<64u)a|=recipe_bits[c];else b|=recipe_bits[c];
 }
 while(lo<hi){
  mid=lo+(hi-lo)/2u;
  if(recipes[mid].a<a||(recipes[mid].a==a&&recipes[mid].b<b))lo=mid+1u;
  else if(recipes[mid].a>a||recipes[mid].b>b)hi=mid;
  else{r=recipes[mid].r;*out=r!=65535u&&((r>>12)&3u)>maximum?65535u:r;return 1;}
 }
 return 0;
}
